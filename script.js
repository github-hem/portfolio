const applyTranslations = (lang) => {
    const dictionary = translations[lang] || translations.en;
    document.documentElement.setAttribute('lang', lang);
    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        if (dictionary[key]) {
            el.textContent = dictionary[key];
        }
    });
    langButtons.forEach((btn) => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });
    localStorage.setItem('preferredLanguage', lang);
    updatePublicationsToggleText(lang);
};

const getTranslation = (lang, key, fallback) => {
    const dictionary = translations[lang] || translations.en;
    return dictionary[key] || fallback;
};

const publicationsSection = document.getElementById('publications');
const publicationsToggle = document.getElementById('publicationsToggle');

let publicationsExpanded = false;

const updatePublicationsToggleText = (lang = (localStorage.getItem('preferredLanguage') || 'en')) => {
    if (!publicationsToggle) return;
    const key = publicationsExpanded ? 'publications.seeLess' : 'publications.seeMore';
    publicationsToggle.textContent = getTranslation(lang, key, publicationsExpanded ? 'See less' : 'See more');
};

const initPublicationsCollapse = () => {
    if (!publicationsSection || !publicationsToggle) return;
    const items = Array.from(publicationsSection.querySelectorAll('.list .list-item'));
    if (items.length <= 10) {
        publicationsToggle.hidden = true;
        return;
    }

    const collapse = () => {
        publicationsExpanded = false;
        items.forEach((item, index) => {
            item.classList.toggle('pub-hidden', index >= 10);
        });
        updatePublicationsToggleText();
        publicationsToggle.setAttribute('aria-expanded', 'false');
    };

    const expand = () => {
        publicationsExpanded = true;
        items.forEach((item) => item.classList.remove('pub-hidden'));
        updatePublicationsToggleText();
        publicationsToggle.setAttribute('aria-expanded', 'true');
    };

    publicationsToggle.addEventListener('click', () => {
        if (publicationsExpanded) collapse();
        else expand();
    });

    publicationsToggle.hidden = false;
    publicationsToggle.setAttribute('aria-controls', 'publications');
    collapse();
};

const openLightbox = (index) => {
    if (!galleryImages.length) {
        return;
    }
    currentIndex = index;
    const target = galleryImages[currentIndex];
    lightboxImage.src = target.src;
    lightboxImage.alt = target.alt || 'Gallery image';
    lightbox.classList.add('open');
    lightbox.setAttribute('aria-hidden', 'false');
};

const closeLightbox = () => {
    lightbox.classList.remove('open');
    lightbox.setAttribute('aria-hidden', 'true');
};

const showNext = () => {
    currentIndex = (currentIndex + 1) % galleryImages.length;
    openLightbox(currentIndex);
};

const showPrev = () => {
    currentIndex = (currentIndex - 1 + galleryImages.length) % galleryImages.length;
    openLightbox(currentIndex);
};

galleryImages.forEach((img, index) => {
    img.addEventListener('click', () => openLightbox(index));
    img.addEventListener('keypress', (event) => {
        if (event.key === 'Enter') {
            openLightbox(index);
        }
    });
    img.style.cursor = 'pointer';
    img.setAttribute('tabindex', '0');
});

lightboxClose?.addEventListener('click', closeLightbox);
lightboxPrev?.addEventListener('click', showPrev);
lightboxNext?.addEventListener('click', showNext);

lightbox?.addEventListener('click', (event) => {
    if (event.target === lightbox) {
        closeLightbox();
    }
});

document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') {
        if (lightbox.classList.contains('open')) closeLightbox();
        else if (document.getElementById('pdfViewer').classList.contains('open')) closePdfViewer();
        return;
    }
    if (!lightbox.classList.contains('open')) return;
    if (event.key === 'ArrowRight') showNext();
    else if (event.key === 'ArrowLeft') showPrev();
});

